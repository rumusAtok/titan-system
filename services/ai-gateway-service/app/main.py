@app.get("/tool-executions", tags=["ai"], summary="Audit log of tool use by the assistant")
async def tool_executions(limit: int = 100, user: Principal = Depends(require_roles("auditor", "tenant_admin"))):
    with app.state.db.tx(user.tenant_id, read_only=True) as conn:
        return conn.execute(
            """SELECT id, username, use_case, tool, arguments, status, detail, duration_ms, selected_by, correlation_id, created_at
                 FROM tool_executions ORDER BY created_at DESC LIMIT %s""",
            (max(1, min(limit, 500)),),
        ).fetchall()
