@app.post("/reports/draft", tags=["reports"], status_code=201, summary="Generate a draft operational report for human review")
async def draft_report(body: ReportRequest, user: Principal = Depends(require_roles(*STAFF))):
    guard_request(user)
    state = await availability()
    ctx = await context(user, state)
    plan_ = [("kpi_summary", {}), ("list_incidents", {"status": "active", "limit": 10}), ("workflow_bottlenecks", {"limit": 5}), ("water_levels", {})]
    sections: dict[str, Any] = {}
    sources: list[dict[str, Any]] = []
    flags: set[str] = set()
    for name, arguments in plan_:
        try:
            result = await tools.execute(ctx, name, arguments, "report_draft", "endpoint", correlation_id.get())
            await announce(user, name, "ok", "report_draft", "endpoint")
            flags |= set(result.flags)
            if not result.empty:
                sections[name] = result.data
                sources.extend(result.sources)
        except tools.ToolError as exc:
            await announce(user, name, exc.status, "report_draft", "endpoint")
            sections[name] = f"Not included: {exc.detail}."
    if not any(not isinstance(v, str) for v in sections.values()):
        return reply("insufficient_evidence", NO_EVIDENCE, state)

    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    deterministic = re.sub(r" \[\d+\]", "", render.daily_report("your organisation", sections, generated_at))
    body_text, generated_by, model = deterministic, "deterministic", None
    if state["mode"] == "model" and not flags:
        mark = guard.boundary()
        records = {k: v for k, v in sections.items() if not isinstance(v, str)}
        prompt = (
            "Write a concise daily operations report with the sections: Summary, Active incidents, Workflow backlog, Water levels. "
            "Start with the line 'DRAFT - requires human review'.\n\n" + guard.wrap_untrusted("RECORDS", json.dumps(records, default=str)[:7000], mark)
        )
        try:
            body_text = await app.state.ollama.chat(guard.SYSTEM_RULES, prompt, max_tokens=700)
            if not body_text.lstrip().upper().startswith("DRAFT"):
                body_text = "DRAFT - requires human review\n\n" + body_text
            generated_by, model = "model", app.state.ollama.chat_model
        except ModelUnavailable:
            pass
    with app.state.db.tx(user.tenant_id) as conn:
        draft = conn.execute(
            """INSERT INTO report_drafts (tenant_id, report_type, title, body, sources, generated_by, model, requested_by)
               VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
               RETURNING id, report_type, title, body, sources, generated_by, model, status, requested_by, created_at""",
            (user.tenant_id, body.report_type, f"Daily operations report {generated_at}", body_text, Jsonb(json.loads(json.dumps(sources, default=str))), generated_by, model, user.username),
        ).fetchone()
    return {**draft, "security_flags": sorted(flags), "evidence": deterministic, "ai": {"mode": state["mode"], "model_available": state["model_available"]}}


