class ChatRequest(BaseModel):
    message: str = Field(min_length=2, max_length=guard.MAX_MESSAGE_CHARS)


_NOTE_PREFIX = re.compile(r"^[\s:,\-]*(saying|that says|with the text)?[\s:,\-]*", re.I)
_UUID = re.compile(r"[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}")


@app.post("/chat", tags=["ai"], summary="Ask a question about operational data the caller is authorised to see")
async def chat(body: ChatRequest, user: Principal = Depends(require_roles(*STAFF))):
    guard_request(user)
    state = await availability()
    message = body.message.strip()
    flags = guard.scan(message)

    if guard.looks_like_write_request(message):
        target = _UUID.search(message)
        # The note is whatever follows the incident id ("...incident <id>: <text>").
        note_text = _NOTE_PREFIX.sub("", message[target.end():]).strip().strip('"') if target else ""
        if target and len(note_text) >= 3 and re.search(r"\badd\b.{0,40}\bnote\b", message, re.I | re.S):
            arguments = {"incident_id": target.group(0), "note": note_text[:1000], "rationale": "Requested in the AI workspace"}
            return await answer_with_tool(user, {**state, "mode": "deterministic"}, "chat", "propose_incident_note", arguments, "rules", message, flags)
        # Recorded, so attempts to make the assistant change data are visible in the audit log.
        with app.state.db.tx(user.tenant_id) as conn:
            conn.execute(
                """INSERT INTO tool_executions (tenant_id, user_id, username, use_case, tool, arguments, status, detail, duration_ms, selected_by, correlation_id)
                   VALUES (%s, %s, %s, 'chat', 'write_request', %s, 'rejected', 'write requests are not executed by the assistant', 0, 'rules', %s)""",
                (user.tenant_id, user.user_id, user.username, Jsonb({"message": message[:500]}), correlation_id.get()),
            )
        await announce(user, "write_request", "rejected", "chat", "rules")
        return reply("refused", CANNOT_WRITE, state, security_flags=flags, tool={"name": "write_request", "status": "rejected"})

    name, arguments, selected_by = await plan(message, state, flags)
    response = await answer_with_tool(user, state, "chat", name, arguments, selected_by, message, flags)
    if response["status"] == "insufficient_evidence" and name != "search_documents":
        # Nothing in operational data: try the approved documents before giving up.
        fallback = await answer_with_tool(user, state, "chat", "search_documents", {"query": message[:300], "limit": 4}, "rules", message, flags)
        if fallback["status"] == "ok":
            return fallback
    return response


