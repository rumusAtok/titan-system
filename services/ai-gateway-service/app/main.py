class ReviewRequest(BaseModel):
    decision: Literal["approve", "reject"]
    note: str | None = Field(None, max_length=1000)


@app.post("/reports/{report_id}/review", tags=["reports"], summary="A person approves or rejects a draft report")
async def review_report(report_id: str, body: ReviewRequest, user: Principal = Depends(require_roles(*REVIEWERS))):
    if not _UUID.fullmatch(report_id):
        raise DomainError.invalid("malformed report id")
    with app.state.db.tx(user.tenant_id) as conn:
        row = conn.execute(
            """UPDATE report_drafts SET status = %s, reviewed_by = %s, review_note = %s, reviewed_at = now()
                WHERE id = %s AND status = 'draft'
                RETURNING id, status, reviewed_by, review_note, reviewed_at""",
            ("approved" if body.decision == "approve" else "rejected", user.username, body.note, report_id),
        ).fetchone()
        if row:
            return row
        exists = conn.execute("SELECT status FROM report_drafts WHERE id = %s", (report_id,)).fetchone()
    if not exists:
        raise DomainError.not_found("report draft")
    raise DomainError.conflict("already_reviewed", f"this draft is already {exists['status']}")


