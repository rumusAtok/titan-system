const AUTHORS = ['analyst', 'tenant_admin', 'department_head', 'incident_commander', 'facility_manager', 'production_supervisor', 'maintenance_planner', 'procurement_officer'];

function NewReportDialog({ open, onClose }: { open: boolean; onClose: () => void }) {
  const client = useQueryClient();
  const datasets = useQuery({ queryKey: ['reports', 'datasets'], queryFn: () => api<any[]>('/api/report/datasets'), enabled: open });
  const usable = (datasets.data ?? []).filter((d) => d.available);
  const [name, setName] = useState('');
  const [description, setDescription] = useState('');
  const [schedule, setSchedule] = useState('none');
  const [notifyRole, setNotifyRole] = useState('');
  const [sections, setSections] = useState<{ title: string; dataset: string; filters: Record<string, string> }[]>([{ title: '', dataset: '', filters: {} }]);
  const create = useMutation({
    mutationFn: () =>
      api('/api/report/definitions', {
        method: 'POST',
        body: {
          name,
          description,
          schedule,
          notify_role: notifyRole || null,
          sections: sections.filter((s) => s.dataset).map((s) => ({ title: s.title || titleCase(s.dataset), dataset: s.dataset, filters: Object.fromEntries(Object.entries(s.filters).filter(([, v]) => v !== '')) })),
        },
      }),
    onSuccess: async () => {
      await client.invalidateQueries({ queryKey: ['reports'] });
      onClose();
    },
  });
  const update = (i: number, patch: Partial<(typeof sections)[number]>) => setSections(sections.map((s, j) => (j === i ? { ...s, ...patch } : s)));
  return (
    <Dialog open={open} onClose={onClose} title="New report" footer={<><Button onClick={onClose}>Cancel</Button><Button variant="primary" type="submit" form="new-report" disabled={create.isPending}>Save report</Button></>}>
      <form id="new-report" className="space-y-3" onSubmit={(e: FormEvent) => { e.preventDefault(); create.mutate(); }}>
        <Field label="Name" required>{(p) => <input {...p} className={inputClass} value={name} onChange={(e) => setName(e.target.value)} />}</Field>
        <Field label="Description">{(p) => <textarea {...p} rows={2} className={inputClass} value={description} onChange={(e) => setDescription(e.target.value)} />}</Field>
        <div className="grid grid-cols-2 gap-3">
          <Field label="Reminder" hint="A reminder when the report is due. It is generated by a person, with their access.">
            {(p) => <select {...p} className={inputClass} value={schedule} onChange={(e) => setSchedule(e.target.value)}>{['none', 'daily', 'weekly', 'monthly'].map((s) => <option key={s} value={s}>{titleCase(s)}</option>)}</select>}
          </Field>
          <Field label="Also remind role">{(p) => <input {...p} className={inputClass} value={notifyRole} placeholder="e.g. incident_commander" onChange={(e) => setNotifyRole(e.target.value)} />}</Field>
        </div>
        {sections.map((s, i) => {
          const ds = usable.find((d) => d.name === s.dataset);
          return (
            <fieldset key={i} className="space-y-2 rounded border border-line p-3">
              <legend className="px-1 text-sm font-medium">Section {i + 1}</legend>
              <Field label="Dataset" required>
                {(p) => (
                  <select {...p} className={inputClass} value={s.dataset} onChange={(e) => update(i, { dataset: e.target.value, filters: {} })}>
                    <option value="">Choose…</option>
                    {usable.map((d) => <option key={d.name} value={d.name}>{d.description}</option>)}
                  </select>
                )}
              </Field>
              <Field label="Section title">{(p) => <input {...p} className={inputClass} value={s.title} onChange={(e) => update(i, { title: e.target.value })} />}</Field>
              {ds && Object.keys(ds.filterable).map((f) => (
                <Field key={f} label={`Only where ${f} =`} hint="Optional filter.">{(p) => <input {...p} className={inputClass} value={s.filters[f] ?? ''} onChange={(e) => update(i, { filters: { ...s.filters, [f]: e.target.value } })} />}</Field>
              ))}
            </fieldset>
          );
        })}
        {sections.length < 8 && <Button type="button" onClick={() => setSections([...sections, { title: '', dataset: '', filters: {} }])}>Add section</Button>}
        <InlineError error={create.error} />
      </form>
    </Dialog>
  );
}

/** Opens the printable HTML of a run in a new tab (fetched with the user's token, shown from a blob). */
async function openHtml(runId: string) {
  const response = await fetch(`${getConfig().gatewayUrl}/api/report/runs/${runId}/html`, { headers: { authorization: `Bearer ${await getToken()}` } });
  if (!response.ok) throw new Error(`Could not open the report (${response.status})`);
  const url = URL.createObjectURL(await response.blob());
  window.open(url, '_blank', 'noopener');
  setTimeout(() => URL.revokeObjectURL(url), 60_000);
}

function RunActions({ run }: { run: any }) {
  const detail = useQuery({ queryKey: ['reports', 'run', run.id], queryFn: () => api<any>(`/api/report/runs/${run.id}`), enabled: run.status === 'completed' });
  const [error, setError] = useState<unknown>(null);
  if (run.status !== 'completed') return <span className="text-sm text-red-700">{run.error}</span>;
  return (
    <span className="flex flex-wrap gap-1">
      <Button onClick={() => openHtml(run.id).catch(setError)}>Open printable</Button>
      <Button onClick={() => download(`/api/report/runs/${run.id}/pdf`, 'report.pdf').catch(setError)}>PDF</Button>
      <Button onClick={() => download(`/api/report/runs/${run.id}/xlsx`, 'report.xlsx').catch(setError)}>Excel</Button>
      {(detail.data?.result ?? []).map((s: any, i: number) => (
        <Button key={i} onClick={() => download(`/api/report/runs/${run.id}/csv?section=${i}`, `${s.dataset}.csv`).catch(setError)}>CSV: {s.title}</Button>
      ))}
      <InlineError error={error} />
    </span>
  );
}

export default function ReportsPage() {
  const active = usePackActive('operational-reporting');
  const { hasRole } = useAuth();
  const [creating, setCreating] = useState(false);
  const definitions = useQuery({ queryKey: ['reports', 'definitions'], queryFn: () => api<any[]>('/api/report/definitions'), enabled: active === true });
  const runs = useQuery({ queryKey: ['reports', 'runs'], queryFn: () => api<any[]>('/api/report/runs'), enabled: active === true });
  if (active === false) return <PackInactive title="Reports" pack="operational reporting" />;
  const defColumns: Column<any>[] = [
    { key: 'name', header: 'Report', value: (d) => d.name, cell: (d) => <span><span className="font-medium">{d.name}</span><br /><span className="text-xs text-ink-muted">{d.sections.map((s: any) => s.dataset).join(', ')}</span></span> },
    { key: 'schedule', header: 'Reminder', value: (d) => d.schedule, cell: (d) => (d.schedule === 'none' ? '—' : `${titleCase(d.schedule)} · next ${dateTime(d.next_due_at)}`) },
    { key: 'owner', header: 'Owner', value: (d) => d.owner_username, cell: (d) => d.owner_username },
    { key: 'last', header: 'Last generated', value: (d) => d.last_generated_at ?? '', cell: (d) => (d.last_generated_at ? <span>{ago(d.last_generated_at)} <StatusBadge status={d.last_run_status} /></span> : 'Never') },
    { key: 'go', header: '', cell: (d) => (d.active ? <ActionButton variant="primary" invalidate={[['reports']]} run={() => api(`/api/report/definitions/${d.id}/generate`, { method: 'POST' })}>Generate now</ActionButton> : 'Inactive') },
  ];
  const runColumns: Column<any>[] = [
    { key: 'name', header: 'Report', value: (r) => r.definition_name, cell: (r) => r.definition_name },
    { key: 'when', header: 'Generated', value: (r) => r.generated_at, cell: (r) => `${dateTime(r.generated_at)} by ${r.generated_by}` },
    { key: 'rows', header: 'Rows', value: (r) => r.total_rows, cell: (r) => r.total_rows, align: 'right' },
    { key: 'status', header: 'Status', value: (r) => r.status, cell: (r) => <StatusBadge status={r.status} /> },
    { key: 'out', header: 'Output', cell: (r) => <RunActions run={r} /> },
  ];
  return (
    <>
      <PageHeader
        title="Reports"
        description="Reports are built from the registered analytics datasets and generated with your own access: nobody sees more in a report than the analytics would show them."
        actions={hasRole(...AUTHORS) && <Button variant="primary" onClick={() => setCreating(true)}>New report</Button>}
      />
      <div className="space-y-6">
        <Card title="Report definitions" padded={false}><QueryView query={definitions} what="Reports">{(rows) => <DataTable caption="Reports" columns={defColumns} rows={rows} rowKey={(d) => d.id} emptyTitle="No reports defined" />}</QueryView></Card>
        <Card title="Generated reports" padded={false}><QueryView query={runs} what="Generated reports">{(rows) => <DataTable caption="Generated reports" columns={runColumns} rows={rows} rowKey={(r) => r.id} emptyTitle="Nothing generated yet" />}</QueryView></Card>
      </div>
      <NewReportDialog open={creating} onClose={() => setCreating(false)} />
    </>
  );
}
